using System.Reflection;
using Comfort.Common;
using EFT;
using EFT.CameraControl;
using LocalSpt5Esp;
using UnityEngine;

int checks = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); checks++; }
Singleton<GameWorld>.Instance = new();
var player = Singleton<GameWorld>.Instance.MainPlayer;
var sight = player.ProceduralWeaponAnimation.CurrentAimingMod;
var manager = CameraManager.Instance.OpticCameraManager;
var camera = manager.Camera;
var updater = manager.Updater;
var handler = new ScopeZoomHandler { _sightComponent = sight };
var firearm = player.HandsController;
handler.OnSmoothSensetivityChangeField = value => { firearm.SmoothFactor = value; firearm.UpdateSensitivity(); };
float NativeSensitivity(float value) => firearm.UserSensitivity * (.7f + (.3f - .7f) * Mathf.InverseLerp(handler.MinFov, handler.MaxFov, value));
bool Near(float actual, float expected) => Math.Abs(actual - expected) <= Math.Max(1e-7f, Math.Abs(expected) * 1e-5f);
updater._scopeZoomHandler = handler;
updater._opticSight = manager.CurrentOpticSight;
manager.CurrentOpticSight.CameraData = new ScopeSmoothCameraData { ScopeZoomHandler = handler };
sight.ScopeZoomValue = 12;

bool Frame(float wheel, bool alt = true)
{
    Time.frameCount++;
    Input.mouseScrollDelta = new(0, wheel);
    Input.Keys.Clear();
    if (alt) Input.Keys.Add(KeyCode.LeftAlt);
    updater.LateUpdate();
    OpticZoom.Tick();
    return handler.OriginalRan;
}

OpticZoom.Initialize(Plugin.Self);
Check(OpticZoom.Enabled.Value, "extended zoom has an enabled-by-default persistent setting");
OpticZoom.Enabled.Value = false;
Check(Frame(30) && handler._currentFieldOfView == 6 && camera.fieldOfView == 6, "disabled feature preserves native clamps");
Check(Frame(-30) && handler._currentFieldOfView == 24 && camera.fieldOfView == 24, "disabled feature preserves native zoom out");
OpticZoom.Enabled.Value = true;
handler._currentFieldOfView = 12;
sight.ScopeZoomValue = 12;
Frame(1);
float oneStep = camera.fieldOfView;
Check(Math.Abs(oneStep - OpticZoomRules.Step(12, 1)) < .0001f, "one wheel delta survives the native final camera write exactly once");
Check(!handler.OriginalRan && sight.ScopeZoomValue == oneStep, "zoom state and sight data use the native handler");
Check(handler.ReticleUpdates > 0 && handler.SensitivityUpdates > 0, "native reticle and sensitivity updates continue");
Check(Near(firearm._aimingSens, NativeSensitivity(oneStep)), "supported zoom retains native sensitivity and user settings");
int events = handler.ZoomEvents;
Frame(0);
Check(camera.fieldOfView == oneStep && handler.ZoomEvents == events, "held zoom survives native updates without repeated change events");
Frame(60);
Check(camera.fieldOfView < 1 && handler._currentFieldOfView == camera.fieldOfView, "native optical zoom exceeds the optic maximum");
Check(handler.MinFov == 24 && handler.MaxFov == 6, "native endpoints are not expanded");
Check(Near(firearm._aimingSens, NativeSensitivity(6) * OpticZoomRules.SensitivityScale(camera.fieldOfView, 6, 24)), "extended zoom reduces actual firearm sensitivity beyond the native endpoint");
float extendedSensitivity = firearm._aimingSens;
Frame(1);
Check(Near(firearm._aimingSens, extendedSensitivity / 1.1f), "each extra magnification step continues to reduce sensitivity");
float stableSensitivity = firearm._aimingSens;
for (int i = 0; i < 5; i++) firearm.UpdateSensitivity();
Check(Near(firearm._aimingSens, stableSensitivity), "repeated native refreshes cannot compound sensitivity scaling");
Frame(-80);
Check(camera.fieldOfView > 24 && Near(firearm._aimingSens, NativeSensitivity(24) * OpticZoomRules.SensitivityScale(camera.fieldOfView, 6, 24)), "zooming below supported magnification raises sensitivity continuously");
handler.ForceChangeScopeState();
Frame(0);
Check(camera.fieldOfView is 6 or 24, "native toggle returns to an original endpoint");
Check(Near(firearm._aimingSens, NativeSensitivity(camera.fieldOfView)), "native toggle restores the endpoint sensitivity");
float firstEndpoint = camera.fieldOfView;
handler.ForceChangeScopeState();
Frame(0);
Check(camera.fieldOfView is 6 or 24 && camera.fieldOfView != firstEndpoint, "native toggle cycles only original endpoints");
Frame(40);
OpticZoom.Enabled.Value = false;
Check(sight.ScopeZoomValue is >= 6 and <= 24, "switching off immediately restores the native sight state");
Check(Near(firearm._aimingSens, NativeSensitivity(sight.ScopeZoomValue)), "switch-off immediately restores native mouse sensitivity");
Frame(0);
Check(handler.OriginalRan && camera.fieldOfView is >= 6 and <= 24, "switching off restores the native camera on its next update");
OpticZoom.Enabled.Value = true;
Frame(40);
Check(Frame(-1, false) && camera.fieldOfView is >= 6 and <= 24, "ordinary zoom input returns to native limits");
Frame(40);
sight.SetScopeMode(0, 1);
Frame(0);
Check(camera.fieldOfView is >= 6 and <= 24, "reticle or scope-mode switching releases extended zoom");
Frame(40);
float held = camera.fieldOfView;
InterfaceMenu.InputBlocked = true;
Frame(10);
Check(camera.fieldOfView == held, "menu input cannot change extended zoom");
InterfaceMenu.InputBlocked = false;
Input.Keys.Add(KeyCode.LeftControl);
Time.frameCount++;
OpticZoom.Tick();
Check(camera.fieldOfView == held, "additional modifiers are excluded");
Input.Keys.Clear();
Input.mouseScrollDelta = new(0, 0);
player.ProceduralWeaponAnimation.IsAiming = false;
OpticZoom.Tick();
Check(handler._currentFieldOfView is >= 6 and <= 24, "leaving ADS restores native handler data");
player.ProceduralWeaponAnimation.IsAiming = true;
camera.Minimum = .5f;
Frame(128);
Check(camera.fieldOfView == .5f && handler._currentFieldOfView == .5f, "native camera readback accepts the engine minimum");
Check(Near(firearm._aimingSens, NativeSensitivity(6) * OpticZoomRules.SensitivityScale(.5f, 6, 24)), "sensitivity follows the accepted engine FOV");
Frame(128);
Check(camera.LastRequested == .5f, "engine limits prevent repeated invalid requests");
camera.Minimum = OpticZoomRules.MinimumFov;
OpticZoom.Enabled.Value = false;
OpticZoom.Enabled.Value = true;

var foreign = new ScopeZoomHandler { _sightComponent = new() };
Time.frameCount++;
Input.mouseScrollDelta = new(0, 1);
Input.Keys.Add(KeyCode.LeftAlt);
float local = handler._currentFieldOfView;
foreign.UpdateFieldOfView();
Check(foreign.OriginalRan && foreign._currentFieldOfView == 11 && handler._currentFieldOfView == local, "foreign zoom handlers keep their native behavior");
var foreignFirearm = new Player.FirearmController();
foreignFirearm.UpdateSensitivity();
Check(Near(foreignFirearm._aimingSens, foreignFirearm.UserSensitivity * foreignFirearm.SmoothFactor), "foreign firearm sensitivity remains native");
firearm._isAiming = false;
float beforeHipFire = firearm._aimingSens;
firearm.UpdateSensitivity();
Check(firearm._aimingSens == beforeHipFire, "inactive native sensitivity updates cannot accumulate a scale");
firearm._isAiming = true;

OpticZoom.Enabled.Value = false;
manager.CurrentOpticSight = new();
manager.CurrentOpticSight.CameraData = new ScopeCameraData { FieldOfView = 12 };
updater._opticSight = manager.CurrentOpticSight;
updater._scopeZoomHandler = null;
OpticZoom.Enabled.Value = true;
Frame(60);
Check(camera.fieldOfView < 1, "fixed optics change through native CopyComponentFromOptic");
Check(Near(firearm._aimingSens, firearm.UserSensitivity * firearm.FixedScopeSensitivity * OpticZoomRules.SensitivityScale(camera.fieldOfView, 12, 12)), "fixed optic mouse sensitivity follows magnification");
Check(((ScopeCameraData)manager.CurrentOpticSight.CameraData).FieldOfView == 12, "fixed optic data is restored after native application");
Frame(0);
Check(camera.fieldOfView < 1, "fixed optic zoom survives the next native update");
OpticZoom.Enabled.Value = false;
Check(camera.fieldOfView == 12, "fixed optic switch-off reapplies native default immediately");
Check(Near(firearm._aimingSens, firearm.UserSensitivity * firearm.FixedScopeSensitivity), "fixed optic switch-off restores native sensitivity");
OpticZoom.Enabled.Value = true;
Frame(30);
OpticZoom.Shutdown();
Check(camera.fieldOfView == 12, "unload restores fixed optic camera data");
Check(Near(firearm._aimingSens, firearm.UserSensitivity * firearm.FixedScopeSensitivity), "unload restores mouse sensitivity");
OpticZoom.Enabled.Value = false;
Check(Plugin.Self.Log.Warnings.Count == 0, "native zoom lifecycle emits no errors");

Console.WriteLine($"PASS {checks} native optic pipeline, toggle, endpoints, fixed optics and unload checks");
