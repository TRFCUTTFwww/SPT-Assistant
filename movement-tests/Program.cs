using Comfort.Common;
using EFT;
using EFT.Interactive;
using LocalSpt5Esp;

int checks=0;
void Check(bool value,string name){if(!value)throw new InvalidOperationException(name);checks++;}
var world=new GameWorld();Singleton<GameWorld>.Instance=world;
var player=world.MainPlayer;var context=player.MovementContext;
var bush=new ObstacleCollider();context._enteredObstacles.Add(bush);
BushMovement.Initialize(Plugin.Self);
context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==.3f&&context.SprintDisabled,"default switch retains native bush limits");
FeatureConfig.Switch.Value=true;BushMovement.Tick(player);
Check(context.SpeedLimit==1&&!context.SprintDisabled,"enabling inside a bush immediately restores speed and sprint");
Check(bush.speedMlp==.3f&&bush._disablesSprint,"shared bush settings are restored after native refresh");
Check(context._bushZoneCount==2&&context._enteredObstacles.Single()==bush,"overlapping bush count and native obstacle membership remain intact");
Check(context.JumpDisabled,"unrelated bush restrictions remain native");
context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==1&&bush.speedMlp==.3f,"subsequent native enter/exit refreshes keep the override without changing shared data");
var other=new ObstacleCollider{speedMlp=.7f,_disablesSprint=true,_hasSwampSpeedLimit=false};context._enteredObstacles.Add(other);
context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==.7f&&context.SprintDisabled,"non-bush obstacle limits remain effective while overlapping a bush");
Check(other.speedMlp==.7f&&other._disablesSprint,"non-bush obstacle settings remain intact");
context._enteredObstacles.Remove(other);
context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==1,"native bush zones bypass independent Swamp_collider objects without TreeInteractive components");
context._bushZoneCount=0;context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==.3f&&context.SprintDisabled,"swamp colliders outside a native bush zone retain their movement restrictions");
context._bushZoneCount=1;context.RefreshObstacleRestrictions();
Check(context.SpeedLimit==1&&!context.SprintDisabled,"entering a bush after its slowdown collider immediately clears both restrictions");
var remote=new MovementContext();remote._enteredObstacles.Add(bush);remote.RefreshObstacleRestrictions();
Check(remote.SpeedLimit==.3f&&remote.SprintDisabled,"remote player context retains native limits on the same shared bush");
context.ThrowOnRefresh=true;
try{context.RefreshObstacleRestrictions();throw new Exception("native exception was swallowed");}catch(InvalidOperationException){}
Check(bush.speedMlp==.3f&&bush._disablesSprint,"finalizer restores shared settings when native refresh throws");
context.ThrowOnRefresh=false;
FeatureConfig.Switch.Value=false;BushMovement.Tick(player);
Check(context.SpeedLimit==.3f&&context.SprintDisabled,"disabling inside a bush immediately restores native restrictions");
FeatureConfig.Switch.Value=true;BushMovement.Tick(player);BushMovement.Reset();
Check(context.SpeedLimit==.3f&&context.SprintDisabled&&FeatureConfig.Switch.Value,"unload restores native restrictions without rewriting the saved switch");
BushMovement.Tick(player);
Check(context.SpeedLimit==1,"a fresh lifecycle reapplies an enabled setting");
var replacement=new MovementContext();replacement._enteredObstacles.Add(bush);player.MovementContext=replacement;BushMovement.Tick(player);
Check(context.SpeedLimit==.3f&&replacement.SpeedLimit==1,"changing movement contexts restores the old context and applies to the new context");
player.HealthController.IsAlive=false;BushMovement.Tick(player);
Check(replacement.SpeedLimit==.3f,"death restores native movement");
replacement.RefreshObstacleRestrictions();Check(replacement.SpeedLimit==.3f,"dead players cannot override native refresh");
player.HealthController.IsAlive=true;RaidClock.Active=false;replacement.RefreshObstacleRestrictions();
Check(replacement.SpeedLimit==.3f,"out-of-raid contexts retain native movement");
RaidClock.Active=true;player.IsYourPlayer=false;replacement.RefreshObstacleRestrictions();
Check(replacement.SpeedLimit==.3f,"non-local owners retain native movement");
player.IsYourPlayer=true;player.Destroyed=true;replacement.RefreshObstacleRestrictions();
Check(replacement.SpeedLimit==.3f,"destroyed players retain native movement");
Check(Plugin.Self.Errors.Count==0,"all valid lifecycle transitions complete without errors");
player.Destroyed=false;replacement._bushZoneCount=0;
FeatureConfig.Switch.Value=false;FeatureConfig.SwampSwitch.Value=true;BushMovement.Tick(player);
Check(replacement.SpeedLimit==1&&!replacement.SprintDisabled,"swamp slowdown has an independent enabled switch");
replacement._bushZoneCount=1;replacement.RefreshObstacleRestrictions();
Check(replacement.SpeedLimit==.3f&&replacement.SprintDisabled,"swamp switch alone cannot bypass bush restrictions");
FeatureConfig.Switch.Value=true;BushMovement.Tick(player);
Check(replacement.SpeedLimit==1&&!replacement.SprintDisabled,"both switches can be enabled together");
FeatureConfig.SwampSwitch.Value=false;BushMovement.Tick(player);replacement._bushZoneCount=0;replacement.RefreshObstacleRestrictions();
Check(replacement.SpeedLimit==.3f&&replacement.SprintDisabled,"bush switch alone cannot bypass independent swamp restrictions");
FeatureConfig.SwampSwitch.Value=true;BushMovement.Tick(player);BushMovement.Reset();
Check(replacement.SpeedLimit==.3f&&replacement.SprintDisabled,"unload restores native swamp restrictions");
FeatureConfig.Switch.Value=false;FeatureConfig.SwampSwitch.Value=false;BushMovement.Tick(player);
Check(replacement.SpeedLimit==.3f&&replacement.SprintDisabled,"disabling both switches preserves native movement");
Console.WriteLine($"PASS {checks} bush movement, shared obstacle restoration and lifecycle checks");
